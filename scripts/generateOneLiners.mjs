import { writeFile } from 'node:fs/promises';
import { books } from '../src/data/parsedBooks.js';
import { bookOneLiners } from '../src/data/bookOneLiners.js';

// Writes src/data/bookOneLiners.js: "what is this book about in one sentence", shown on
// the book cards (the full summary is only shown in the detail drawer).
//
// Usage: node scripts/generateOneLiners.mjs [--force] [--limit N]
// Only books without a one-liner are processed unless --force. Edit a line in the
// output file by hand to correct it; reruns keep existing entries.

try {
  process.loadEnvFile();
} catch (_) {}
try {
  process.loadEnvFile('.env.local');
} catch (_) {}

const apiKey = process.env.OPENAI_API_KEY || process.env.VITE_OPENAI_API_KEY;
const MODEL = 'gpt-4.1';
const BATCH_SIZE = 15;
const CONCURRENCY = 4;
const FORCE = process.argv.includes('--force');
const limitArg = process.argv.indexOf('--limit');
const LIMIT = limitArg > -1 ? Number(process.argv[limitArg + 1]) : Infinity;
const OUT_PATH = new URL('../src/data/bookOneLiners.js', import.meta.url);

const SYSTEM_PROMPT = `You write the one-sentence answer to "What is this book about?" for cards in a personal book collection.
For each book return one_liner: a single plain sentence of 12-22 words saying what the book is about and its angle or argument.
- Do not start with the title, the author's name, "This book" or "A book"; start with the substance (e.g. "How a handful of mathematicians beat Wall Street by trusting models over instinct.").
- A sentence fragment that begins with "How", "Why", "The story of", "A guide to" etc. is fine.
- No hype words ("must-read", "gripping", "compelling"), no quotation marks, no emoji.
- Use only what the given summary supports; invent no specifics.`;

const SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['books'],
  properties: {
    books: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['id', 'one_liner'],
        properties: { id: { type: 'integer' }, one_liner: { type: 'string' } },
      },
    },
  },
};

async function generateBatch(batch) {
  const payload = batch.map((b) => ({ id: b.id, title: b.title, author: b.author, summary: b.summary }));
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch('https://api.openai.com/v1/chat/completions', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${apiKey}` },
        body: JSON.stringify({
          model: MODEL,
          temperature: 0.3,
          response_format: { type: 'json_schema', json_schema: { name: 'one_liners', strict: true, schema: SCHEMA } },
          messages: [
            { role: 'system', content: SYSTEM_PROMPT },
            { role: 'user', content: JSON.stringify(payload) },
          ],
        }),
      });
      if (!res.ok) throw new Error(`OpenAI error (${res.status}): ${await res.text()}`);
      const data = await res.json();
      return JSON.parse(data.choices[0].message.content).books;
    } catch (err) {
      if (attempt >= 3) throw err;
      await new Promise((r) => setTimeout(r, 2000 * attempt));
    }
  }
}

async function main() {
  if (!apiKey) {
    console.error('\n❌ OPENAI_API_KEY is not set.\n');
    process.exit(1);
  }
  const todo = books.filter((b) => FORCE || !bookOneLiners[b.title]).slice(0, LIMIT);
  console.log(`\n📚 Writing one-liners for ${todo.length} of ${books.length} books with ${MODEL}...`);

  const out = { ...bookOneLiners };
  const batches = [];
  for (let i = 0; i < todo.length; i += BATCH_SIZE) batches.push(todo.slice(i, i + BATCH_SIZE));

  let done = 0;
  let next = 0;
  async function worker() {
    while (next < batches.length) {
      const batch = batches[next++];
      const byId = new Map((await generateBatch(batch)).map((r) => [r.id, r.one_liner.trim()]));
      for (const book of batch) {
        const line = byId.get(book.id);
        if (line) out[book.title] = line;
        else console.warn(`\n⚠️  No result for "${book.title}"`);
      }
      done += batch.length;
      process.stdout.write(`\r  ${done}/${todo.length}`);
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  const body = Object.entries(out)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([title, line]) => `  ${JSON.stringify(title)}: ${JSON.stringify(line)},`)
    .join('\n');
  await writeFile(
    OUT_PATH,
    `// "What is this book about in one sentence" — shown on book cards.\n` +
      `// Generated by scripts/generateOneLiners.mjs; hand edits are kept on rerun.\n` +
      `export const bookOneLiners = {\n${body}\n};\n`,
  );
  console.log(`\n🎉 Wrote src/data/bookOneLiners.js`);
}

main().catch((err) => {
  console.error('\nFatal error:', err);
  process.exit(1);
});
